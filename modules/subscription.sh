#!/usr/bin/env bash
set -Eeuo pipefail
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../lib/common.sh disable=SC1091
source "$SCRIPT_DIR/../lib/common.sh"

# ---- nginx 订阅站点（原 modules/web.sh 并入，见 v3.3.0 精简重构）----
# 独立 nginx 站点：不依赖发行版默认站点的 root 恰好是 /var/www/html
NGINX_CONF="/etc/nginx/sites-available/proxy-manager.conf"
NGINX_LINK="/etc/nginx/sites-enabled/proxy-manager.conf"

write_nginx_conf() {
  # 仅当内核启用 IPv6 时写入 [::]:80，避免无 IPv6 的机器上 nginx 启动失败
  local v6=""
  [[ -f /proc/net/if_inet6 ]] && v6="listen [::]:80 default_server;"
  cat >"$NGINX_CONF" <<EOF
# Generated by Proxy Manager — subscription serving (:80 default_server)
server {
    listen 80 default_server;
    ${v6}
    server_name _;
    root /var/www/html;
    index index.html index.nginx-debian.html;

    # 订阅文件位于 /var/www/html/clash/<随机令牌>/config.yaml（路径不可猜测）
    location /clash/ {
        autoindex off;
        add_header Cache-Control "no-store";
    }
}
EOF
}

# 启用本站点并停用发行版默认站点（避免 default_server 冲突）；校验失败自动回滚
configure_nginx() {
  local had_default=0
  [[ -e /etc/nginx/sites-enabled/default || -L /etc/nginx/sites-enabled/default ]] && had_default=1
  write_nginx_conf
  ln -sfn "$NGINX_CONF" "$NGINX_LINK"
  if [[ "$had_default" == 1 ]]; then rm -f /etc/nginx/sites-enabled/default; fi
  if nginx -t >/dev/null 2>&1; then
    systemctl reload nginx 2>/dev/null || systemctl restart nginx
    say "nginx 订阅站点已启用（proxy-manager.conf 接管 :80 default_server）。"
  else
    say "⚠ nginx 配置校验失败，输出如下："
    nginx -t 2>&1 || true
    rm -f "$NGINX_LINK"
    if [[ "$had_default" == 1 ]]; then ln -sfn /etc/nginx/sites-available/default /etc/nginx/sites-enabled/default; fi
    nginx -t >/dev/null 2>&1 && systemctl reload nginx 2>/dev/null || true
    die "nginx 配置失败，已回滚到原状态。请检查上方 nginx -t 输出。"
  fi
}

# ---- 订阅生成 ----
generate() {
  load_node_data || return 1
  install -d -m 0755 "$WEB_ROOT"
  # NODE_NAME 兜底：v3.3.0 重构时把旧版 ${NODE_NAME:-Reality-$SERVER} 的兜底弄丢了。
  # 脚本开着 set -u，若 node.env 缺 NODE_NAME，下面 heredoc 展开 "$NODE_NAME" 会直接
  # 以 unbound variable 退出——此时令牌目录已建、config.yaml 没写，订阅 URL 变 404/空文件。
  local name="${NODE_NAME:-Reality-$SERVER}"
  # 订阅随机令牌：订阅路径不可猜测。固定路径 /clash/config.yaml 会被扫段者直接取走
  # 含 UUID 的节点配置（UUID 即 VLESS 唯一凭证）。
  if [[ -z "${SUB_TOKEN:-}" ]]; then
    require_command openssl
    SUB_TOKEN="$(openssl rand -hex 16)"
    env_upsert "$NODE_FILE" SUB_TOKEN "$SUB_TOKEN"
  fi
  SUBSCRIPTION_URL="http://$SERVER/clash/$SUB_TOKEN/config.yaml"
  env_upsert "$NODE_FILE" SUBSCRIPTION_URL "$SUBSCRIPTION_URL"
  chmod 0600 "$NODE_FILE"
  local sub_dir="$WEB_ROOT/$SUB_TOKEN"
  install -d -m 0755 "$sub_dir"
  cat >"$sub_dir/config.yaml" <<EOF
# Generated by Proxy Manager; this file contains no server private key.
mixed-port: 7890
allow-lan: false
mode: rule
log-level: warning
ipv6: false
unified-delay: true
tcp-concurrent: true
packet-encoding: xudp
dns:
  enable: true
  ipv6: false
  enhanced-mode: fake-ip
  fake-ip-range: 198.18.0.1/16
  listen: 127.0.0.1:1053
  nameserver:
    - https://1.1.1.1/dns-query
    - https://8.8.8.8/dns-query
  fallback:
    - https://dns.google/dns-query
    - https://1.0.0.1/dns-query
  proxy-server-nameserver:
    - https://1.1.1.1/dns-query
proxies:
  - name: "$name"
    type: vless
    server: "$SERVER"
    port: $PORT
    uuid: "$UUID"
    encryption: "none"
    network: tcp
    udp: true
    tls: true
    flow: xtls-rprx-vision
    servername: "$SNI"
    client-fingerprint: chrome
    reality-opts:
      public-key: "$PUBLIC_KEY"
      short-id: "$SHORT_ID"
EOF
  # 备用链路：Hysteria2（UDP + 端口跳跃）。仅在 node.env 记录 HY2=1 时生成。
  # 自签证书 → skip-cert-verify；ports 为 Mihomo 的端口跳跃字段。
  if [[ "${HY2:-0}" == "1" && -n "${HY2_PASSWORD:-}" ]]; then
    systemctl is-active --quiet hysteria-server 2>/dev/null \
      || say "⚠ 注意: HY2=1 但 hysteria-server 未运行，订阅里的 Hysteria2 节点暂不可用（可运行 Xray 菜单 6 重装）。"
    cat >>"$sub_dir/config.yaml" <<EOF
  - name: "HY2-$SERVER"
    type: hysteria2
    server: "$SERVER"
    port: ${HY2_PORT:-443}
    ports: "${HY2_HOP:-20000-40000}"
    password: "$HY2_PASSWORD"
    sni: "${HY2_SNI:-$name}"
    skip-cert-verify: true
    up: "100 Mbps"
    down: "500 Mbps"
EOF
  fi
  cat >>"$sub_dir/config.yaml" <<EOF
proxy-groups:
  - name: Proxy
    type: select
    proxies:
      - "$name"
EOF
  if [[ "${HY2:-0}" == "1" && -n "${HY2_PASSWORD:-}" ]]; then
    printf '      - "HY2-%s"\n' "$SERVER" >>"$sub_dir/config.yaml"
  fi
  cat >>"$sub_dir/config.yaml" <<EOF
      - DIRECT
  - name: Auto
    type: url-test
    url: "http://www.gstatic.com/generate_204"
    interval: 300
    tolerance: 50
    proxies:
      - "$name"
EOF
  if [[ "${HY2:-0}" == "1" && -n "${HY2_PASSWORD:-}" ]]; then
    printf '      - "HY2-%s"\n' "$SERVER" >>"$sub_dir/config.yaml"
  fi
  cat >>"$sub_dir/config.yaml" <<EOF
rules:
  # 回国流量：国内域名/IP 直连，不走代理（按需可改为 REJECT）
  - GEOIP,CN,DIRECT
  - DOMAIN-SUFFIX,cn,DIRECT
  - MATCH,Proxy
EOF
  chmod 0644 "$sub_dir/config.yaml"
  # 迁移：删除旧版固定路径订阅文件，令可猜测地址彻底失效
  rm -f "$WEB_ROOT/config.yaml"
  # 清理历史令牌目录：node.env 重建（重装 / 换密钥）后 SUB_TOKEN 会变，旧令牌目录仍留在
  # WEB_ROOT 下 —— 旧订阅 URL 继续返回 HTTP 200，但内容是不再匹配服务端的过期节点参数，
  # 客户端表现为「订阅能拉取成功、节点却全部超时」。只清理 32 位十六进制命名的令牌目录，
  # 避免误删用户自己放进去的文件。
  local stale base
  for stale in "$WEB_ROOT"/*; do
    [[ -d "$stale" ]] || continue
    base="$(basename "$stale")"
    if [[ "$base" =~ ^[0-9a-f]{32}$ && "$base" != "$SUB_TOKEN" ]]; then
      rm -rf "$stale"
      say "已清理过期订阅目录: $base（其旧 URL 不再返回过期节点）"
    fi
  done
  # 自检：历史问题为 nginx 未启动导致订阅空/不可用
  [[ -s "$sub_dir/config.yaml" ]] || die "Clash 配置生成失败（文件为空）。"
  # 自检：内容必须与当前节点参数一致，防止写入旧变量 / 旧模板
  grep -q "uuid: \"$UUID\"" "$sub_dir/config.yaml" \
    || die "生成的 Clash 配置 UUID 与节点不一致，请重跑生成。"
  grep -q "port: $PORT" "$sub_dir/config.yaml" \
    || die "生成的 Clash 配置端口与节点不一致，请重跑生成。"
  if ! systemctl is-active --quiet nginx 2>/dev/null; then
    say "⚠ 自检: nginx 未运行，订阅 URL 暂时无法访问 —— 生成后发布即可（本菜单选项 1 会自动完成）。"
  elif command -v curl >/dev/null 2>&1; then
    local code
    code=$(curl -o /dev/null -s -w '%{http_code}' "http://127.0.0.1/clash/$SUB_TOKEN/config.yaml" || true)
    if [[ "$code" == "200" ]]; then say "✓ 自检: 订阅 URL 本地可访问 (HTTP 200)。"; else say "⚠ 自检: 本地请求返回 HTTP ${code:-无响应}（若仅本机测不到公网 IP 属正常，请以浏览器访问为准）。"; fi
  fi
  say "URL: $SUBSCRIPTION_URL"
  say "⚠ 订阅地址含随机令牌，等同节点凭证，请勿泄露。"
}

# ---- 发布（幂等）：配置 nginx 站点并放行 80 ----
publish() {
  # 注意：这里必须 return 1 而不是 require_command（后者会 die/exit，
  # 会把调用它的 generate_and_publish 与整个菜单一起带走）
  command -v nginx >/dev/null 2>&1 || { say "⚠ 未安装 nginx，订阅文件仅在服务器本地可用。"; return 1; }
  install -d -m 0755 "$WEB_ROOT"
  systemctl enable --now nginx
  configure_nginx
  command -v ufw >/dev/null && ufw status | grep -q 'Status: active' && ufw allow 80/tcp || true
  load_node_data || return 1
  say "已发布：${SUBSCRIPTION_URL:-订阅地址见上方输出}"
}

# 生成后自动发布（幂等）：让「安装节点 → 订阅可访问」一步到位
generate_and_publish() {
  generate || return 1
  if command -v nginx >/dev/null 2>&1; then
    say "--- 发布订阅站点 ---"
    publish || return 1
  else
    say "⚠ 未安装 nginx：订阅文件已生成，但公网无法访问。安装 nginx 后重跑本菜单选项 1 即可发布。"
  fi
}

case "${1:-}" in
  generate) require_root; generate; exit;;
  publish)  require_root; publish; exit;;
  show)     load_node_data || exit 1; say "${SUBSCRIPTION_URL:-订阅尚未生成，请先执行生成。}"; exit;;
  "") ;;
  *) die "Usage: subscription.sh [generate|publish|show]";;
esac

require_root
while true; do
  clr; say "===== Clash 订阅与发布 ====="
  say "1. 生成并发布订阅"; say "2. 显示订阅地址"; say "3. 重新发布 nginx 站点"; say "4. 查看 nginx 状态"; say "0. 返回"
  read -r -p "请选择: " c
  case "$c" in
    1) if generate_and_publish; then :; else say "（未成功完成，原因见上方输出）"; fi
       read -r -p "请按回车继续..." _ || true;;
    2) if load_node_data; then say "${SUBSCRIPTION_URL:-订阅尚未生成，请先执行生成。}"; fi
       read -r -p "请按回车继续..." _ || true;;
    3) if publish; then :; else say "（未成功完成，原因见上方输出）"; fi
       read -r -p "请按回车继续..." _ || true;;
    4) systemctl --no-pager status nginx || true
       read -r -p "请按回车继续..." _ || true;;
    0) exit;;
    *) say "无效选择。";;
  esac
done
